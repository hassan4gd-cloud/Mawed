package com.mawid.app;

import static org.junit.Assert.assertEquals;

import java.time.LocalDateTime;
import org.junit.Test;

/** اختبارات المحلّل على رسائل نموذجية (التاريخ المرجعي: الأحد 15/11/2026 الساعة 10:00). */
public class SmartParserTest {

    private static void check(String text, String now, String expWhen, String expTitle) {
        SmartParser.Result r = SmartParser.parse(text, LocalDateTime.parse(now));
        if (expWhen != null) assertEquals(text, expWhen, r.when.toString());
        if (expTitle != null) assertEquals(text, expTitle, r.title);
    }

    @Test
    public void parsesSampleMessages() {
        String N = "2026-11-15T10:00";
        check("لدي موعد عند الساعة 2 مع مدير الشركة", N, "2026-11-15T14:00", "موعد مع مدير الشركة");
        check("اجتماع بكرا الساعة ١٠ ونص الصبح مع فريق التصميم", N, "2026-11-16T10:30", "اجتماع مع فريق التصميم");
        check("نذكركم بموعدكم يوم الخميس القادم الساعة 4:15 مساءً في عيادة د. أحمد", N, "2026-11-19T16:15", "موعد في عيادة د. أحمد");
        check("Meeting with the CEO tomorrow at 3pm", N, "2026-11-16T15:00", "Meeting with the CEO");
        check("مقابلة عمل بتاريخ 20/11/2026 الساعة التاسعة صباحاً", N, "2026-11-20T09:00", "مقابلة عمل");
        check("بعد ساعتين عندي اتصال مع العميل", N, "2026-11-15T12:00", "اتصال مع العميل");
        check("حفلة عيد ميلاد سارة يوم السبت الساعة الثامنة مساء", N, "2026-11-21T20:00", "حفلة عيد ميلاد سارة");
        check("موعد الدكتور الساعة 9", N, "2026-11-15T21:00", "موعد الدكتور");
        check("موعد الدكتور الساعة 9", "2026-11-15T08:00", "2026-11-15T09:00", null);
        check("تذكير: دفع الإيجار 25 تشرين الثاني", N, "2026-11-25T09:00", "دفع الإيجار");
        check("الاجتماع الساعة 3 إلا ربع", N, "2026-11-15T14:45", "اجتماع");
        check("المحاضرة الساعة ٣:٣٠ م", N, "2026-11-15T15:30", "محاضرة");
        check("عندك اجتماع مع المدير العام الساعة 11 قبل الظهر", N, "2026-11-15T11:00", "اجتماع مع المدير العام");
        check("مرحبا أستاذ حسان، نود إعلامكم بأن اجتماع مجلس الإدارة سيكون يوم الثلاثاء 10:00 صباحاً", N, "2026-11-17T10:00", null);
        check("Your appointment is on Nov 20 at 4:30 PM with Dr. Smith", N, "2026-11-20T16:30", null);
        check("مكالمة مع أبو خالد بعد نص ساعة", N, "2026-11-15T10:30", "مكالمة مع أبو خالد");
        check("الساعة ٨ بالليل عشاء عند أبو أحمد", N, "2026-11-15T20:00", null);
        check("غداً الساعة الواحدة ظهراً تسليم المشروع", N, "2026-11-16T13:00", "تسليم المشروع");
        check("يوم الأحد الساعة 2", N, "2026-11-15T14:00", null);
        check("يوم الأحد الساعة 9 الصبح", N, "2026-11-22T09:00", null);
        check("جلسة تصوير 2026-12-01 الساعة 17:00", N, "2026-12-01T17:00", "جلسة تصوير");
        check("موعد مع طبيب الأسنان الساعة 1", "2026-11-15T15:00", "2026-11-16T13:00", "موعد مع طبيب الأسنان");
        check("بكرا الساعة 12", N, "2026-11-16T12:00", null);
        check("Interview next Monday at 9:30am", N, "2026-11-16T09:30", "Interview");
        check("call me in 20 minutes", N, "2026-11-15T10:20", null);
        check("الساعة اتنعش الضهر غدا اجتماع", N, "2026-11-16T12:00", null);
        check("مرحبا كيف حالك", N, null, null);
        check("موعد الحلاق الساعة سبعة ونص المسا", N, "2026-11-15T19:30", "موعد الحلاق");
        check("درس اللغة 15 شهر 12 الساعة 5", N, "2026-12-15T17:00", "درس اللغة");
    }
}
